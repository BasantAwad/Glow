"""
Routes wired to session history (Phase 3 session_records + session_messages).
Provides real session listing, detail, and doctor-summary export for the
/reflections frontend.
"""

from __future__ import annotations

import datetime
from typing import Annotated

from fastapi import APIRouter, Depends
from pydantic import BaseModel
from sqlalchemy import desc, select
from sqlalchemy.ext.asyncio import AsyncSession

from glow_api.crypto import EnvelopeEncryption
from glow_api.database import get_db_session
from glow_api.dependencies import get_current_user
from glow_api.kms import kms_service
from glow_api.models import (
    SessionMessageModel,
    SessionRecordModel,
    UserAccountModel,
)
from glow_api.user import UserAccount

router = APIRouter(tags=["session_history"])


# ---------------------------------------------------------------------------
# Schemas
# ---------------------------------------------------------------------------

class SessionSummaryResponse(BaseModel):
    id: int
    session_id: str
    state: str
    mode: str
    created_at: datetime.datetime
    started_at: datetime.datetime | None
    closed_at: datetime.datetime | None
    is_crisis: bool
    closure_reason: str | None
    message_count: int
    preview: str | None  # first assistant message, truncated


class DoctorSummaryResponse(BaseModel):
    session_id: str
    session_date: str
    duration_minutes: int | None
    mood_note: str | None
    preview: str
    full_text: str


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _decrypt_message(blob: bytes, key_id: str) -> str:
    key = kms_service.get_master_key(key_id)
    return EnvelopeEncryption.decrypt(key, blob[:12], blob[12:]).decode("utf-8")


def _build_preview(msgs: list[SessionMessageModel]) -> str | None:
    """First non-empty assistant message, truncated to ~200 chars."""
    for m in msgs:
        if m.role == "assistant":
            text = _decrypt_message(m.encrypted_content, m.key_id)
            if text.strip():
                return (text[:200] + "…") if len(text) > 200 else text
    return None


def _build_doctor_summary(session: SessionRecordModel, preview: str) -> str:
    started = session.started_at
    closed = session.closed_at
    duration = None
    if started and closed:
        duration = int((closed - started).total_seconds() / 60)

    date_str = started.strftime("%Y-%m-%d") if started else "unknown"
    duration_str = f"{duration} min" if duration else "unknown"

    return f"""SESSION SUMMARY
Date: {date_str}
Duration: {duration_str}
Mode: {session.mode}
State: {session.state}
{"Crisis session" if session.is_crisis else "Non-crisis session"}

WHAT WAS SHARED:
{preview or "(no transcript available)"}

NOTES:
- This summary was generated by Glow, an AI support tool.
- It is not a medical document — use it as a conversation starter
  with your healthcare provider.
- If physical symptoms were mentioned (sleep, appetite, energy, pain),
  consider asking a doctor about possible medical causes (thyroid,
  anemia, vitamin levels, etc.).
"""


# ---------------------------------------------------------------------------
# Routes
# ---------------------------------------------------------------------------


@router.get("/sessions", response_model=list[SessionSummaryResponse])
async def list_sessions(
    user: Annotated[UserAccount, Depends(get_current_user)],
    db: Annotated[AsyncSession, Depends(get_db_session)],
) -> list[SessionSummaryResponse]:
    """List the authenticated user's sessions (most recent first)."""
    uid = (
        await db.execute(
            select(UserAccountModel.id).where(
                UserAccountModel.user_id == user.user_id
            )
        )
    ).scalar_one()
    rows = (
        await db.execute(
            select(SessionRecordModel)
            .where(SessionRecordModel.user_account_id == uid)
            .order_by(desc(SessionRecordModel.created_at))
            .limit(50)
        )
    ).scalars().all()

    out: list[SessionSummaryResponse] = []
    for s in rows:
        msgs = (
            await db.execute(
                select(SessionMessageModel)
                .where(SessionMessageModel.session_record_id == s.id)
                .order_by(SessionMessageModel.timestamp.asc())
            )
        ).scalars().all()
        preview = _build_preview(msgs)
        out.append(
            SessionSummaryResponse(
                id=s.id,
                session_id=s.session_id,
                state=s.state,
                mode=s.mode,
                created_at=s.created_at,
                started_at=s.started_at,
                closed_at=s.closed_at,
                is_crisis=s.is_crisis,
                closure_reason=s.closure_reason,
                message_count=len(msgs),
                preview=preview,
            )
        )
    return out


@router.get("/sessions/{session_id}", response_model=SessionSummaryResponse)
async def get_session(
    session_id: str,
    user: Annotated[UserAccount, Depends(get_current_user)],
    db: Annotated[AsyncSession, Depends(get_db_session)],
) -> SessionSummaryResponse:
    """Get a single session's summary (owned by the authenticated user)."""
    uid = (
        await db.execute(
            select(UserAccountModel.id).where(
                UserAccountModel.user_id == user.user_id
            )
        )
    ).scalar_one()
    s = (
        await db.execute(
            select(SessionRecordModel)
            .where(SessionRecordModel.session_id == session_id)
            .where(SessionRecordModel.user_account_id == uid)
        )
    ).scalar_one_or_none()
    if s is None:
        from glow_api.errors import NotFoundError
        raise NotFoundError(detail="Session not found")

    msgs = (
        await db.execute(
            select(SessionMessageModel)
            .where(SessionMessageModel.session_record_id == s.id)
            .order_by(SessionMessageModel.timestamp.asc())
        )
    ).scalars().all()
    preview = _build_preview(msgs)
    return SessionSummaryResponse(
        id=s.id,
        session_id=s.session_id,
        state=s.state,
        mode=s.mode,
        created_at=s.created_at,
        started_at=s.started_at,
        closed_at=s.closed_at,
        is_crisis=s.is_crisis,
        closure_reason=s.closure_reason,
        message_count=len(msgs),
        preview=preview,
    )


@router.get("/sessions/{session_id}/doctor-summary", response_model=DoctorSummaryResponse)
async def get_doctor_summary(
    session_id: str,
    user: Annotated[UserAccount, Depends(get_current_user)],
    db: Annotated[AsyncSession, Depends(get_db_session)],
) -> DoctorSummaryResponse:
    """Generate a doctor-shareable summary for a session."""
    uid = (
        await db.execute(
            select(UserAccountModel.id).where(
                UserAccountModel.user_id == user.user_id
            )
        )
    ).scalar_one()
    s = (
        await db.execute(
            select(SessionRecordModel)
            .where(SessionRecordModel.session_id == session_id)
            .where(SessionRecordModel.user_account_id == uid)
        )
    ).scalar_one_or_none()
    if s is None:
        from glow_api.errors import NotFoundError
        raise NotFoundError(detail="Session not found")

    msgs = (
        await db.execute(
            select(SessionMessageModel)
            .where(SessionMessageModel.session_record_id == s.id)
            .order_by(SessionMessageModel.timestamp.asc())
        )
    ).scalars().all()
    preview = _build_preview(msgs) or "(no transcript available)"
    full_text = _build_doctor_summary(s, preview)
    started = s.started_at
    duration = None
    if started and s.closed_at:
        duration = int((s.closed_at - started).total_seconds() / 60)

    return DoctorSummaryResponse(
        session_id=s.session_id,
        session_date=started.strftime("%Y-%m-%d") if started else "unknown",
        duration_minutes=duration,
        mood_note=None,
        preview=preview,
        full_text=full_text,
    )
